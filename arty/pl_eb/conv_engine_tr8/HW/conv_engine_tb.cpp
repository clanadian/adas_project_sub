static int8_t clamp_i8(int64_t v) {
    if (v > 127)  return 127;
    if (v < -128) return -128;
    return (int8_t)v;
}

// round(x / 2^s), ties away from zero - plain int64_t implementation of the
// same RTL_HANDOFF_KO.md section 5 formula conv_engine.cpp's round_shift()
// implements in ap_int<64>. Written independently here (not calling into
// conv_engine.cpp, whose round_shift()/apply_activation() are file-local
// static functions anyway) so a bug in one has no way to silently agree
// with the other - same "no shared code path" reasoning this function's
// caller already documents for the conv math itself.
static int64_t round_shift_ref(int64_t x, unsigned s) {
    if (s == 0) return x;
    int64_t half = (int64_t)1 << (s - 1);
    return (x >= 0) ? ((x + half) >> s) : -(((-x) + half) >> s);
}

// Independent reference convolution - deliberately NOT sharing any code path
// with conv_engine.cpp (no shared window/line-buffer structure), so a bug in
// conv_engine's raster-scan indexing has no way to silently agree with this.
static void reference_conv(
    const std::vector<int8_t> &x, const std::vector<int8_t> &w, const std::vector<int32_t> &b,
    std::vector<int8_t> &out,
    unsigned img_h, unsigned img_w, unsigned in_ch, unsigned out_ch,
    unsigned k, unsigned pad,
    bool leaky_relu_enable, int32_t requant_multiplier, unsigned requant_shift
) {
    unsigned out_h = img_h + 2 * pad - k + 1;
    unsigned out_w = img_w + 2 * pad - k + 1;
    out.assign((size_t)out_h * out_w * out_ch, 0);

    for (unsigned r = 0; r < out_h; r++) {
        for (unsigned c = 0; c < out_w; c++) {
            for (unsigned oc = 0; oc < out_ch; oc++) {
                int64_t acc = b[oc];
                for (unsigned ic = 0; ic < in_ch; ic++) {
                    for (unsigned ky = 0; ky < k; ky++) {
                        for (unsigned kx = 0; kx < k; kx++) {
                            int in_r = (int)r + (int)ky - (int)pad;
                            int in_c = (int)c + (int)kx - (int)pad;
                            int8_t px = 0;
                            if (in_r >= 0 && in_r < (int)img_h &&
                                in_c >= 0 && in_c < (int)img_w) {
                                px = x[((size_t)in_r * img_w + in_c) * in_ch + ic];
                            }
                            unsigned w_idx = ((oc * in_ch + ic) * k + ky) * k + kx;
                            acc += (int64_t)px * (int64_t)w[w_idx];
                        }
                    }
                }
                // RTL_HANDOFF_KO.md section 5, in order: LeakyReLU(13/128) on
                // the raw accumulator (only if negative), THEN per-layer
                // requantize, THEN saturate - NOT the old placeholder
                // "acc>=0 ? acc : acc>>3" this replaces.
                if (leaky_relu_enable && acc < 0) {
                    acc = round_shift_ref(acc * 13, 7);
                }
                int64_t scaled = acc * (int64_t)requant_multiplier;
                int64_t activated = round_shift_ref(scaled, requant_shift);
                out[((size_t)r * out_w + c) * out_ch + oc] = clamp_i8(activated);
            }
        }
    }
}

// Self-test of the INT8 DSP-packing primitive (conv_engine.h's
// packed_weight_t, and the pack/unpack math in conv_engine.cpp's
// load_weight_tile()/scan_and_compute()), run in isolation before the
// config sweep below. RESOURCE_BUDGET.md §5 flags this exact technique as
// "getting it wrong silently produces wrong math rather than a synthesis
// error" - split into two passes rather than one, for a reason found the
// hard way (see below).
//
// Pass 1 (pack_unpack_selftest_fast): exhaustively brute-forces ALL
// 256*256*256 = 16,777,216 (X, Y_lo, Y_hi) triples, but using PLAIN native
// integer arithmetic that emulates the exact same mask/shift/sign-extend
// operations, not real ap_int types. This is what actually matters for
// correctness - it's what caught the original missing "+1 carry when the
// low field's sign bit is set" bug, which was a math error, not an
// ap_int-specific one. It runs in well under a second.
//
// Pass 2 (pack_unpack_selftest_ap_int_sample): confirms the REAL ap_int/HLS
// types (packed_weight_t, .range(), signed shifts, casts) behave exactly
// like pass 1's plain-int model - but only over a much smaller, deliberately
// chosen set (all sign/magnitude corner cases + a fixed reproducible random
// sample), not the full 16.7M. Running the full exhaustive sweep through
// real ap_int arithmetic was tried first and made C-sim impractically
// slow (looked "stuck") - ap_int's arbitrary-precision simulation model
// pays real per-operation overhead that a native int does not, and at
// 16.7M iterations that overhead compounds into minutes-to-hours instead
// of seconds. This pass exists only to catch an ap_int-semantics surprise
// (e.g. if `.range()`'s sign-reinterpretation behaved differently than
// assumed) that pass 1 - being plain-int - could not catch on its own.
//
// Both are pure C++ host-side tests - never synthesized, no __SYNTHESIS__
// guard needed.
static void pack_unpack_selftest_fast() {
    for (int xi = -128; xi <= 127; xi++) {
        for (int yhi = -128; yhi <= 127; yhi++) {
            for (int ylo = -128; ylo <= 127; ylo++) {
                uint32_t y_lo_biased = (uint8_t)ylo ^ 0x80u;
                int64_t packed = ((int64_t)yhi << 16) | y_lo_biased;
                int64_t product = (int64_t)xi * packed;

                int32_t low16 = (int32_t)(product & 0xFFFF);
                if (low16 & 0x8000) low16 -= 0x10000; // sign-extend, matches ap_int<16>

                int64_t contrib_hi = product >> 16; // matches ap_int's arithmetic shift
                if (low16 < 0) contrib_hi += 1;      // the carry correction under test
                int64_t contrib_lo = low16 - ((int64_t)xi << 7);

                if (contrib_hi != (int64_t)xi * yhi || contrib_lo != (int64_t)xi * ylo) {
                    printf("pack_unpack_selftest_fast FAIL: x=%d y_lo=%d y_hi=%d "
                           "-> contrib_lo=%lld (want %d) contrib_hi=%lld (want %d)\n",
                           xi, ylo, yhi, (long long)contrib_lo, xi * ylo,
                           (long long)contrib_hi, xi * yhi);
                    assert(false && "packed MAC split algorithm mismatch");
                }
            }
        }
    }
    printf("pack_unpack_selftest_fast: 16,777,216 combinations (plain-int model) PASS\n");
}

static void pack_unpack_selftest_ap_int_sample() {
    auto check_one = [](int xi, int ylo, int yhi) {
        act_t x = (act_t)xi;
        weight_t y_hi = (weight_t)yhi;
        weight_t y_lo = (weight_t)ylo;

        // Mirrors load_weight_tile()'s pack step exactly.
        ap_uint<8> y_lo_biased = (ap_uint<8>)y_lo ^ (ap_uint<8>)0x80;
        packed_weight_t packed =
            (((ap_int<25>)y_hi) << 16) + (ap_int<25>)y_lo_biased;

        // Mirrors scan_and_compute()'s MAC_KX unpack step exactly, including
        // the +1 carry correction on contrib_hi.
        ap_int<33> product = x * packed;
        ap_int<16> l_signed = product.range(15, 0);
        accum_t contrib_hi = (accum_t)(product >> 16);
        if (l_signed < 0) {
            contrib_hi += 1;
        }
        accum_t contrib_lo = (accum_t)l_signed - ((accum_t)x << 7);

        if (contrib_hi != xi * yhi || contrib_lo != xi * ylo) {
            printf("pack_unpack_selftest_ap_int_sample FAIL: x=%d y_lo=%d y_hi=%d "
                   "-> contrib_lo=%d (want %d) contrib_hi=%d (want %d)\n",
                   xi, ylo, yhi, (int)contrib_lo, xi * ylo,
                   (int)contrib_hi, xi * yhi);
            assert(false && "packed MAC split ap_int-type mismatch");
        }
    };

    // All sign/magnitude corner cases: 6*6*6 = 216 combinations, covering
    // every boundary the split logic's correctness actually depends on
    // (most negative, most positive, +-1, zero).
    const int corners[] = {-128, -127, -1, 0, 1, 127};
    for (int xi : corners)
        for (int yhi : corners)
            for (int ylo : corners)
                check_one(xi, ylo, yhi);

    // Fixed, reproducible pseudo-random sample across the full range, to
    // catch anything the hand-picked corners above might miss - small
    // enough to stay fast even at ap_int's simulation speed.
    srand(12345);
    for (int i = 0; i < 20000; i++) {
        int xi  = (rand() % 256) - 128;
        int ylo = (rand() % 256) - 128;
        int yhi = (rand() % 256) - 128;
        check_one(xi, ylo, yhi);
    }

    printf("pack_unpack_selftest_ap_int_sample: 216 corner + 20,000 random "
           "combinations (real ap_int types) PASS\n");
}

// Runs one config through conv_engine() and checks it against reference_conv().
// Returns 0 on PASS, 1 on FAIL (mirrors conv_layer1_tb.cpp's convention).
//
// `pad_to_full_depth` (default false): when true, allocates the four
// host-side arrays passed to conv_engine() at the FULL m_axi depth
// (IFMAP_DEPTH etc. above) instead of this config's actual (much smaller)
// dimensions - only actually needed for C/RTL co-simulation (see the
// comment on those constants). Defaults to false because plain C-sim
// never reads `depth` at all, and unconditionally paying for ~200M-element
// allocations across all 8 configs (tried first) made ordinary C-sim
// dramatically slower - the same category of problem as the exhaustive
// ap_int self-test's slowdown (TROUBLESHOOTING.md §7), just ~100x more
// ap_int-construction work (1.6 billion elements across 8 configs vs. that
// entry's 16.7 million). Only the one dedicated cosim config in main()
// passes true - cosim's job is checking the tool's C-to-RTL translation
// fidelity on a representative case, not re-proving algorithm correctness
// across edge cases, which the other 8 configs already do exhaustively via
// fast, small-buffer C-sim.
static int run_config(
    const char *name,
    unsigned img_h, unsigned img_w, unsigned in_ch, unsigned out_ch,
    unsigned k, unsigned pad, unsigned seed,
    bool leaky_relu_enable, int32_t requant_multiplier, unsigned requant_shift,
    bool pad_to_full_depth = false,
    // 2026-08-19: 0 보다 크면 **이 형상이 실제로 포화를 밟는지** 검사한다.
    // 포화 커버리지 형상을 추가해 놓고 파라미터가 바뀌어 더 이상 포화를
    // 안 밟게 되면, PASS 는 계속 나오면서 커버리지만 조용히 사라진다.
    // 그것이 이 저장소에서 가장 비싼 실패 유형이라 숫자로 못박는다.
    double min_sat_pct = 0.0, double max_sat_pct = 100.0
) {
    srand(seed);

    std::vector<int8_t>  x((size_t)img_h * img_w * in_ch);
    std::vector<int8_t>  w((size_t)out_ch * in_ch * k * k);
    std::vector<int32_t> b(out_ch);

    for (auto &v : x) v = (int8_t)((rand() % 41) - 20);
    for (auto &v : w) v = (int8_t)((rand() % 11) - 5);
    // Wider range than weight_t's [-5,4] above - bias is now signed INT32
    // (bias_t, matching the golden model's bias.bin), so this exercises
    // values a plain INT8 bias never could.
    for (auto &v : b) v = (int32_t)((rand() % 2001) - 1000);

    std::vector<int8_t> ref_out;
    reference_conv(x, w, b, ref_out, img_h, img_w, in_ch, out_ch, k, pad,
                   leaky_relu_enable, requant_multiplier, requant_shift);

    unsigned out_h = img_h + 2 * pad - k + 1;
    unsigned out_w = img_w + 2 * pad - k + 1;

    size_t ifmap_size   = pad_to_full_depth ? IFMAP_DEPTH   : x.size();
    size_t weights_size = pad_to_full_depth ? WEIGHTS_DEPTH : w.size();
    size_t bias_size    = pad_to_full_depth ? BIAS_DEPTH    : b.size();
    size_t ofmap_size   = pad_to_full_depth ? OFMAP_DEPTH   : (size_t)out_h * out_w * out_ch;

    // Only the front sub-region (this config's real data) is filled when
    // pad_to_full_depth is set; the rest stays zero-padding that
    // conv_engine() never reads or writes, since its own loop bounds come
    // from img_h/img_w/in_ch/out_ch/k, not from how large the underlying
    // buffer happens to be.
    // PACK4: only the ifmap buffer is word-allocated - every other port
    // keeps its original element type. See pack4_words()/pack4_put() below.
    std::vector<pack4_t> x_hw(pack4_words(ifmap_size), (pack4_t)0);
    // WPACK: weights are word-allocated now too (repack_weights_okkxi).
    std::vector<pack4_t> w_hw(pack4_words(weights_size), (pack4_t)0);
    std::vector<bias_t> b_hw(bias_size, (bias_t)0);
    std::vector<act_t> hw_out(ofmap_size, (act_t)0);

    for (size_t i = 0; i < x.size(); i++) pack4_put(x_hw, i, x[i]);
    repack_weights_okkxi(w_hw, w.data(), out_ch, in_ch, k);
    std::copy(b.begin(), b.end(), b_hw.begin());

    // w_hw.data() passed twice - weights_hi is a second, independent m_axi
    // port aliasing the SAME weight data (see conv_engine.h's note on this
    // param), not a separate buffer. In real hardware, software programs
    // both address registers with the same DRAM base address; here in C-sim
    // the equivalent is simply reusing the same host-side vector.
    conv_engine(
        x_hw.data(), w_hw.data(), w_hw.data(), b_hw.data(), hw_out.data(),
        (uint16_t)img_h, (uint16_t)img_w, (uint16_t)in_ch, (uint16_t)out_ch,
        (uint8_t)k, /*stride=*/1, (uint8_t)pad,
        requant_multiplier, (uint8_t)requant_shift, (uint8_t)(leaky_relu_enable ? 1 : 0)
    );

    unsigned mismatches = 0;
    unsigned total = out_h * out_w * out_ch;
    for (unsigned i = 0; i < total; i++) {
        int8_t hw_val = (int8_t)hw_out[i];
        int8_t ref_val = ref_out[i];
        if (hw_val != ref_val) {
            if (mismatches < 10) {
                printf("  [%s] MISMATCH at flat idx=%u: hw=%d ref=%d\n",
                       name, i, hw_val, ref_val);
            }
            mismatches++;
        }
    }

    if (mismatches == 0) {
        unsigned sat = 0;
        for (unsigned i = 0; i < total; i++)
            if (ref_out[i] == 127 || ref_out[i] == -128) sat++;
        double sat_pct = total ? 100.0 * (double)sat / (double)total : 0.0;
        printf("[%s] PASS: %u output values matched the reference bit-exactly "
               "(img %ux%ux%u -> %ux%ux%u, k=%u, pad=%u) [포화 %.1f%%]\n",
               name, total, img_w, img_h, in_ch, out_w, out_h, out_ch, k, pad,
               sat_pct);
        if (min_sat_pct > 0.0 && (sat_pct < min_sat_pct || sat_pct > max_sat_pct)) {
            printf("  [%s] FAIL: 포화 커버리지 %.1f%% 가 요구 구간 "
                   "[%.1f%%, %.1f%%] 밖이다 - 이 형상은 더 이상 포화 경로를 "
                   "시험하지 않는다\n", name, sat_pct, min_sat_pct, max_sat_pct);
            return 1;
        }
        return 0;
    } else {
        printf("[%s] FAIL: %u/%u values mismatched\n", name, mismatches, total);
        return 1;
    }
}


