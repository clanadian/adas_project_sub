// Full m_axi interface depths - must match conv_engine.cpp's `#pragma HLS
// INTERFACE m_axi ... depth=...` expressions exactly. C/RTL co-simulation
// builds its RTL bus-functional-model's memory image from the host pointer
// using this depth, regardless of how much of it a given call's actual
// img_h/img_w/in_ch/out_ch/k dimensions use - passing a host array smaller
// than `depth` makes cosim read past the end of the allocation (SIGSEGV
// during ENTER_WRAPC; see TROUBLESHOOTING.md's cosim entry). Plain C-sim
// never uses `depth` at all, so this was never needed until cosim was
// attempted.
// ifmap/weights depths now scale with MAX_TOTAL_IN_CH (1024), not MAX_IN_CH
// (128) - see conv_engine.cpp's matching m_axi depth= pragmas for why
// (input-channel tiling: on-chip buffers stay MAX_IN_CH-wide, but the DDR
// arrays they're tiled slices of must be addressable across a layer's real
// total in_ch).
static const size_t IFMAP_DEPTH   = (size_t)MAX_IMG_W * MAX_IMG_W * MAX_TOTAL_IN_CH;

// ---- PACK4 testbench helpers ----------------------------------------------
// conv_engine's `ifmap` port is now pack4_t (4 consecutive NHWC channels per
// 32-bit beat, see HW/pack4.h), so the tb's ifmap buffer is allocated and
// passed in WORDS. Every other port is unchanged.
//
// The reference_conv() model and all the golden arrays stay entirely
// int8_t-based and completely unaware of the packing - that is what makes a
// PASS here evidence the packing is bit-exact, rather than evidence that
// both sides share the same packing bug.
//
// IFMAP_DEPTH above stays in ELEMENTS so it still reads as the same
// img/ch bound product the engine's depth= pragma uses; pack4_words()
// converts at each point of use.
static inline size_t pack4_words(size_t elems) {
    return (elems + PACK4_LANES - 1) / PACK4_LANES;
}

// Flat int8 element index -> (word, lane), matching pack4.h's little-endian
// lane order: lane 0 is the lowest channel index and the low byte. This is
// the mapping the DDR byte layout already had, which is why no PS-side
// repacking is needed in real hardware - it is spelled out here only
// because the tb holds its golden data in a separate int8_t array.
static inline void pack4_put(std::vector<pack4_t> &buf, size_t elem_idx, int8_t v) {
    pack4_set(buf[elem_idx / PACK4_LANES], (unsigned)(elem_idx % PACK4_LANES), (ap_int<8>)v);
}
// WPACK: weights move from OIHW ([oc][ic][ky][kx], ic stride k*k) to
// [oc][ky][kx][ic] (ic stride 1, innermost) so that one 4-byte AXI beat
// carries FOUR DIFFERENT ic. That is the whole point: `wtile_packed` is
// already ARRAY_PARTITION cyclic factor=TR on its ic dimension, so 4
// different ic land in 4 different banks and the existing partitioning
// absorbs the write with no change. Packing along the old innermost axis
// (kx) instead would put 4 values of the SAME ic in one beat, which
// collides on that bank and would need ky/kx partitioned complete -
// 256 -> 2304 banks, i.e. BRAM blowup. See the plan doc's
// "[design decision] option (A), keeping the layout unchanged, dies on resources".
//
// This runs host-side because on real hardware it is the PS that writes the
// weight buffer into DDR; the layout is a SW contract, not a golden-data
static void repack_weights_okkxi(std::vector<pack4_t> &dst, const int8_t *src,
                                 unsigned out_ch, unsigned in_ch, unsigned k) {
    for (unsigned oc = 0; oc < out_ch; oc++)
        for (unsigned ic = 0; ic < in_ch; ic++)
            for (unsigned ky = 0; ky < k; ky++)
                for (unsigned kx = 0; kx < k; kx++) {
                    size_t s = ((size_t)(oc * in_ch + ic) * k + ky) * k + kx;
                    size_t d = ((size_t)(oc * k + ky) * k + kx) * in_ch + ic;
                    pack4_put(dst, d, src[s]);
                }
}

static const size_t WEIGHTS_DEPTH = (size_t)MAX_OUT_CH * MAX_TOTAL_IN_CH * MAX_K * MAX_K;
static const size_t BIAS_DEPTH    = (size_t)MAX_OUT_CH;
static const size_t OFMAP_DEPTH   = (size_t)MAX_IMG_W * MAX_IMG_W * MAX_OUT_CH;
