// C-simulation testbench for conv_engine.
//
// Unlike conv_layer1_tb.cpp (which drives ONE fixed, compile-time-sized
// layer), this testbench exists specifically to prove the engine's core
// claim: that it produces correct output across DIFFERENT runtime
// geometries, not just the one shape it happens to be compiled for. It runs
// eleven deliberately different configs (A-K, see main() below) through the
// same conv_engine() call, each exercising a different edge case (multi-tile
// output-channel tiling, k=1, minimal channel counts, the MAX_IN_CH boundary,
// a non-multiple-of-TR reduction, non-square images, a pe-pair straddling
// the out_ch boundary after a preceding full tile (config H, added for this
// project's INT8 DSP-packing experiment), and - configs I/J/K, added once
// the real network showed input-channel tiling was needed, see
// conv_engine.h - multi-pass ic_tile coverage with and without a remainder,
// and both oc_tile/ic_tile tiling happening at once), plus one dedicated
// "config-A-cosim" repeat of config-A sized for C/RTL
// co-simulation specifically (see run_config()'s pad_to_full_depth
// parameter). Before the config sweep, main() also runs
// pack_unpack_selftest_fast() (exhaustive, plain-int) and
// pack_unpack_selftest_ap_int_sample() (a smaller ap_int-typed confirmation
// pass) - see the comment above their definitions for why it's split into
// two rather than one.
//
// Sizes are intentionally small (not the real 416x416 Phase 1 input) - this
// suite is about proving runtime-parameterization correctness quickly, not
// about exercising the real network's actual layer sizes. The real sizes
// only matter once this passes and the design moves to hardware bring-up
// (SW/network_run.c) on actual silicon, per doc/05_learning/hls-study-plan.md's phased
// approach. Only "config-A-cosim" pays the cost of full-m_axi-depth host
// buffers (IFMAP_DEPTH etc. below) - the other 8 configs stay at their
// actual, small per-config sizes, since plain C-sim never reads `depth` at
// all and paying that cost on every config (tried first) made ordinary
// C-sim dramatically slower for no benefit to it.
